import { NutritionFields } from '@/types/food.types';

export const calculateTotalNutrition = (
  ingredients: Array<{ nutrition?: Partial<NutritionFields> }>,
): NutritionFields =>
  ingredients.reduce(
    (acc, ingredient) => {
      if (ingredient.nutrition) {
        for (const key of Object.keys(acc) as Array<keyof NutritionFields>) {
          const value = ingredient.nutrition[key];
          if (value !== undefined) {
            acc[key] += Number(value) || 0;
          }
        }
      }
      return acc;
    },
    {
      carbs: 0,
      fat: 0,
      proteins: 0,
      calories: 0,
      netCarbs: 0,
      caffeine: 0,
      theobromine: 0,
      fiber: 0,
      calcium: 0,
      iron: 0,
      magnesium: 0,
      phosphorus: 0,
      potassium: 0,
      sodium: 0,
      zinc: 0,
      copper: 0,
      fluoride: 0,
      manganese: 0,
      selenium: 0,
      vitAIu: 0,
      vitA: 0,
      vitB6: 0,
      vitB12: 0,
      vitC: 0,
      vitDIu: 0,
      vitD: 0,
      vitD2: 0,
      vitD3: 0,
      vitE: 0,
      vitK: 0,
      retinol: 0,
      lycopene: 0,
      thiamine: 0,
      riboflavin: 0,
      niacin: 0,
      folate: 0,
      choline: 0,
      betaCarotene: 0,
      alphaCarotene: 0,
      cholesterol: 0,
      betaine: 0,
      sugar: 0,
      sucrose: 0,
      glucose: 0,
      fructose: 0,
      lactose: 0,
      maltose: 0,
      galactose: 0,
      starch: 0,
      alcohol: 0,
      water: 0,
      tryptophan: 0,
      threonine: 0,
      isoleucine: 0,
      leucine: 0,
      lysine: 0,
      methionine: 0,
      cystine: 0,
      phenylalanine: 0,
      tyrosine: 0,
      valine: 0,
      arginine: 0,
      histidine: 0,
      alanine: 0,
      asparticAcid: 0,
      glycine: 0,
      proline: 0,
      serine: 0,
      hydroxyproline: 0,
      transFats: 0,
      saturatedFats: 0,
      monounsaturatedFats: 0,
      polyunsaturatedFats: 0,
      alaFattyAcid: 0,
      dhaFattyAcid: 0,
      epaFattyAcid: 0,
      dpaFattyAcid: 0,
      totalOmega3: 0,
      totalOmega6: 0,
    } as NutritionFields,
  );
